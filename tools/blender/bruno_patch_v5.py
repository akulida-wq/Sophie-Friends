# Bruno patch v5 — тело переходит в ноги + детализация по референсу.
# Что нового против v4:
#   1. Ноги — продолжение тела: корпус (metaball) плавно раздваивается
#      в две ноги, отдельных "палок" больше нет; низ тела мягко
#      прискиннен к костям ног (Walk/SitAlone гнут само тело).
#   2. Кепка ещё меньше (-18%), с тёмно-розовой окантовкой и пуговкой.
#   3. Тонкое верхнее веко над глазом (характер, как на арте).
#   4. Пятая веснушка на каждой щеке (размеры варьируются).
#   5. Руки выгнуты наружу сильнее, крепятся выше, сглажены.
#   6. Кости рига скрыты после сборки (это они выглядели как "Софи";
#      вернуть: глаз у Bruno_Rig в Outliner).
#
# Это структурная переделка тела -> проще пересобрать целиком, чем
# латать: скрипт сносит коллекцию "Bruno" и запускает билдер (v5).
# Твоя сцена и Софи не затрагиваются. Вставь в Text Editor -> Run Script.
import bpy

BUILDER = "/Users/artur/Desktop/Overdone/Sophie game mock/tools/blender/build_bruno.py"

# ---------- 1. снести старого Бруно (если был) ----------
D = bpy.data
removed = 0
old = D.collections.get("Bruno")
if old:
    for o in list(old.objects):
        D.objects.remove(o, do_unlink=True)
        removed += 1
    D.collections.remove(old)

# ---------- 2. собрать заново билдером (уже v5) ----------
_code = open(BUILDER).read()
exec(compile(_code, BUILDER, "exec"), {"__file__": BUILDER, "__name__": "__main__"})

print(f"Patch v5: пересобран (удалено {removed} старых объектов). "
      f"Тело переходит в ноги, кепка -18% с окантовкой, веко, 5-я веснушка.")
